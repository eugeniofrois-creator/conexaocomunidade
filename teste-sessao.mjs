import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const load=async f=>import('data:text/javascript;base64,'+Buffer.from(await readFile(f,'utf8')).toString('base64'));
const {ContasRepositorio}=await load('./contas-repositorio.js');
const {AuthIndividual}=await load('./auth-individual.js');
const rows=new Map();let n=0;
const store={async read(p){const r=rows.get(p);return r?structuredClone(r):null},async write(p,data,revision=null){const old=rows.get(p);if((old?.revision||null)!==revision)throw Error('conflito');const r={data:structuredClone(data),revision:String(++n)};rows.set(p,r);return {revision:r.revision}}};
const mem=()=>{const m=new Map();return {getItem:k=>m.get(k)||null,setItem:(k,v)=>m.set(k,v),removeItem:k=>m.delete(k)}};
const c=new ContasRepositorio(store),a=new AuthIndividual(c,mem(),mem());
await a.handle('POST',{action:'register-company',username:'empresa_teste',name:'Empresa Teste',email:'teste@example.test',password:'uma senha de teste longa'});
assert.equal((await a.handle('GET')).user.role,'company');
await a.handle('POST',{action:'logout'});assert.equal((await a.handle('GET')).user,null);
await assert.rejects(()=>a.handle('POST',{username:'empresa_teste',password:'incorreta'}));
await a.handle('POST',{username:'empresa_teste',password:'uma senha de teste longa',remember:'true'});
assert.ok((await a.handle('GET')).user.expires>Date.now());
await a.handle('POST',{action:'password',currentPassword:'uma senha de teste longa',password:'uma nova senha bem longa'});
assert.equal((await a.handle('GET')).user,null);
await assert.rejects(()=>a.handle('POST',{username:'empresa_teste',password:'uma senha de teste longa'}));
assert.equal((await a.handle('POST',{username:'empresa_teste',password:'uma nova senha bem longa'})).role,'company');
console.log('OK: cadastro, login, manutenção de sessão, logout e mudança de senha.');
